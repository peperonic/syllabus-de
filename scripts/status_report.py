"""Write STATUS.md from a built knowledge base: per Land and subject, what is
inventoried, fetched, parsed and certified, and how reliable the validity data is.

    python3 scripts/status_report.py [--data-dir data] [--out STATUS.md]
"""
from __future__ import annotations

import argparse
import datetime as dt
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from kb.pack import load_pack  # noqa: E402

Q = """
SELECT d.land, d.subject,
       COUNT(*) docs,
       SUM(d.sha256 IS NOT NULL) fetched,
       SUM(d.validity_confidence = 'stated') v_stated,
       SUM(d.validity_confidence = 'inferred') v_inferred,
       SUM(d.validity_confidence = 'needs_review') v_review,
       (SELECT COUNT(*) FROM curriculum_node n JOIN document x ON x.document_id = n.document_id
          WHERE x.land = d.land AND x.subject = d.subject) nodes,
       (SELECT COUNT(*) FROM edge e JOIN curriculum_node n ON n.node_id = e.src JOIN document x ON x.document_id = n.document_id
          WHERE e.rel = 'maps_to' AND e.certified = 1 AND x.land = d.land AND x.subject = d.subject) certified
FROM document d GROUP BY d.land, d.subject ORDER BY d.land, d.subject
"""


def stage(r) -> str:
    if r["certified"]:
        return "certified"
    if r["nodes"]:
        return "parsed"
    if r["fetched"]:
        return "fetched"
    return "inventory only"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack")
    ap.add_argument("--data-dir")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "STATUS.md"))
    a = ap.parse_args(argv)
    pack = load_pack(a.pack, a.data_dir)
    c = sqlite3.connect(pack.db_path)
    c.row_factory = sqlite3.Row
    lands = {r["code"]: r for r in c.execute("SELECT * FROM land")}
    rows = c.execute(Q).fetchall()
    runs = c.execute("SELECT stage, MAX(finished_at) t FROM build_run GROUP BY stage ORDER BY stage").fetchall()
    out = ["# Status", "",
           f"Generated by `scripts/status_report.py` on {dt.date.today().isoformat()} from `{pack.db_path.name}`. "
           "Do not edit by hand; rebuild and regenerate.", "",
           "Stages run: " + (", ".join(f"{r['stage']} ({r['t'][:10]})" for r in runs) or "none"), "",
           "Validity columns count the S0b reading of each document's start date and rollout: "
           "**stated** (read from the inventory text), **inferred** (assumed, see `validity_note`), "
           "**review** (not determinable, needs a person).", "",
           "| Land | Subject | Docs | Fetched | Nodes | Certified mappings | Validity stated / inferred / review | Stage |",
           "|---|---|---:|---:|---:|---:|---|---|"]
    for r in rows:
        land = r["land"] + (" (placeholder)" if lands.get(r["land"]) and lands[r["land"]]["inventory_status"] == "placeholder" else "")
        out.append(f"| {land} | {r['subject']} | {r['docs']} | {r['fetched']} | {r['nodes']} | {r['certified']} | "
                   f"{r['v_stated']} / {r['v_inferred']} / {r['v_review']} | {stage(r)} |")
    tot = c.execute("SELECT COUNT(*), SUM(sha256 IS NOT NULL), SUM(validity_confidence='needs_review') FROM document").fetchone()
    out += ["", f"Total: {tot[0]} documents, {tot[1] or 0} fetched, {tot[2] or 0} with validity needing review.", ""]
    Path(a.out).write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
